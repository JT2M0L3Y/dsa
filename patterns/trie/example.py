class TrieNode:
    def __init__(self):
        self.children = {}
        self.is_end = False

class Trie:
    def __init__(self):
        self.root = TrieNode()

    def insert(self, word):
        node = self.root
        for ch in word:
            if ch not in node.children:
                node.children[ch] = TrieNode()
            node = node.children[ch]
        node.is_end = True

    def contains(self, word):
        node = self.root
        for ch in word:
            if ch not in node.children:
                return False
            node = node.children[ch]
        return node.is_end

if __name__ == "__main__":
    trie = Trie()
    for word in ["apple", "app", "banana"]:
        trie.insert(word)
    print(trie.contains("app"), trie.contains("banana"), trie.contains("apricot"))
